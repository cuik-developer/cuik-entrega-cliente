function groupOf(ruc: string): DigitGroup | null {
  const d = ruc.trim().slice(-1)
  switch (d) {
    case "0":
      return "0"
    case "1":
      return "1"
    case "2":
    case "3":
      return "2-3"
    case "4":
    case "5":
      return "4-5"
    case "6":
    case "7":
      return "6-7"
    case "8":
    case "9":
      return "8-9"
    default:
      return null
  }
}

/** Due date of the PDT 621 of `month` for this RUC, or null when the year is not loaded. */
export function pdtDueDate(month: string, ruc: string): string | null {
  const g = groupOf(ruc)
  return g ? (SCHEDULE[month]?.[g] ?? null) : null
}
