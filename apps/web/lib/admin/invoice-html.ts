export function esc(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;")
}

const money = (n: number, currency: UblInvoice["currency"]) =>
  `${currency === "USD" ? "US$" : "S/"} ${n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`

const qty = (n: number) =>
  Number.isInteger(n) ? String(n) : n.toLocaleString("en-US", { maximumFractionDigits: 3 })

/** "2026-11-16" → "16/11/2026". */
export function dmy(iso: string): string {
  const m = iso.match(/^(\d{4})-(\d{2})-(\d{2})$/)
  return m ? `${m[3]}/${m[2]}/${m[1]}` : esc(iso)
}

/** Unit value: 2 decimals for one unit; up to 4 when several, so qty × value matches the line. */
const unitMoney = (n: number, quantity: number, currency: UblInvoice["currency"]) =>
  quantity === 1
    ? money(n, currency)
    : `${currency === "USD" ? "US$" : "S/"} ${n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 4 })}`

