/** "2026-11", 1 → "noviembre 2026"; "2026-11", 3 → "noviembre 2026 – enero 2027". */
export function periodLabel(period: string, months: number): string | null {
  const m = period.match(/^(\d{4})-(\d{2})$/)
  if (!m) return null
  const y = Number(m[1])
  const mo = Number(m[2]) - 1
  if (mo < 0 || mo > 11) return null
  const name = (i: number) => `${MONTHS[i % 12]} ${y + Math.floor(i / 12)}`
  const n = Math.max(1, Math.floor(months))
  return n === 1 ? name(mo) : `${name(mo)} – ${name(mo + n - 1)}`
}

