/**
 * The Cuik-branded printed invoice: one A4 HTML page (inline CSS, brand
 * palette and Poppins) built from the SUNAT XML. Every value from the XML or
 * the database is HTML-escaped; the only script is the print helper, allowed
 * by the nonce the route puts in its Content-Security-Policy.
 */
export type BrandedInvoiceInput = {
  inv: UblInvoice
  issuer: {
    razonSocial: string
    ruc: string
    domicilioFiscal: string | null
    paymentInfo: string | null
    thanks: string | null
  }
  /** Customer address when the XML has none (SEE-SOL leaves it out). */
  customerAddressFallback: string | null
  /** "noviembre 2026" or "noviembre 2026 – enero 2027"; null = no period row. */
  periodLabel: string | null
  /** SVG markup of the SUNAT QR (generated by the route, trusted). */
  qrSvg: string
  logoUrl: string
  nonce: string
  autoPrint: boolean
}

